using System;
using System.Collections.Generic;
using System.Linq;
using AxePower.Core.Models.Music;
using AxePower.Core.Services.Music;

namespace AxePower.Tests.Music;

/// <summary>
/// Picking the right recording out of a search. The cases are the ones that actually went wrong:
/// a live take the same length as the studio one, an hour-long loop, and a karaoke upload.
/// </summary>
public class CandidateRankerTests
{
    private static Track Wanted(string title, string artist, double minutes = 3.3, string? album = null) =>
        Track.ForProvider(new ProviderRef("spotify", "x"), title, new[] { artist },
            TimeSpan.FromMinutes(minutes), album);

    private static StreamCandidate Hit(string title, string channel, double minutes) =>
        new(title, title, new ProviderRef("youtube", title), channel, TimeSpan.FromMinutes(minutes));

    private static string Best(Track track, params StreamCandidate[] candidates) =>
        CandidateRanker.Rank(track, candidates)[0].Title;

    [Fact]
    public void TheStudioTrackBeatsALiveTakeOfTheSameLength()
    {
        // The real failure: the live version was 3:19 and the studio one 3:24, so ordering by
        // duration alone against a 3:18 target put the live take first.
        var track = Wanted("Blinding Lights", "The Weeknd", 3.3);

        string best = Best(track,
            Hit("The Weeknd - Blinding Lights (Live On The 2020 MTV VMAs)", "The Weeknd", 3.316),
            Hit("The Weeknd - Blinding Lights (Lyrics)", "Lyrics Vault", 3.333),
            Hit("The Weeknd - Blinding Lights (Official Audio)", "The Weeknd", 3.4));

        Assert.Equal("The Weeknd - Blinding Lights (Official Audio)", best);
    }

    [Fact]
    public void AnHourLongLoopIsNeverChosenForAThreeMinuteTrack()
    {
        var track = Wanted("Blinding Lights", "The Weeknd");

        var ranked = CandidateRanker.Rank(track, new[]
        {
            Hit("The Weeknd - Blinding Lights (Lyrics) - 1 Hour", "Loop Nation", 61),
            Hit("The Weeknd - Blinding Lights", "The Weeknd - Topic", 3.35)
        });

        Assert.Equal("The Weeknd - Blinding Lights", ranked[0].Title);
    }

    [Fact]
    public void AnAutoGeneratedTopicChannelWinsOverAThirdPartyReupload()
    {
        var track = Wanted("Halo", "Beyonce", 4.4);

        string best = Best(track,
            Hit("Halo", "MusicUploads123", 4.4),
            Hit("Halo", "Beyonce - Topic", 4.4));

        Assert.Equal("Halo", CandidateRanker.Rank(track, new[]
        {
            Hit("Halo", "MusicUploads123", 4.4),
            Hit("Halo", "Beyonce - Topic", 4.4)
        })[0].Title);

        Assert.Equal("Beyonce - Topic", CandidateRanker.Rank(track, new[]
        {
            Hit("Halo", "MusicUploads123", 4.4),
            Hit("Halo", "Beyonce - Topic", 4.4)
        })[0].Artist);
    }

    [Fact]
    public void KaraokeAndInstrumentalUploadsSinkBelowTheRealRecording()
    {
        var track = Wanted("Yesterday", "The Beatles", 2.1);

        var ranked = CandidateRanker.Rank(track, new[]
        {
            Hit("Yesterday - Karaoke Version", "SingAlong", 2.1),
            Hit("Yesterday (Instrumental)", "Backing Tracks", 2.1),
            Hit("The Beatles - Yesterday", "The Beatles - Topic", 2.1)
        });

        // Karaoke and instrumental are equally wrong, so which of the two comes last is not
        // worth asserting; what matters is that the real recording is ahead of both.
        Assert.Equal("The Beatles - Yesterday", ranked[0].Title);
        Assert.Equal(2, ranked.Count(c => c.Title != "The Beatles - Yesterday"));
        Assert.True(CandidateRanker.Score(track, ranked[0]) > CandidateRanker.Score(track, ranked[1]));
    }

    [Fact]
    public void AskingForALiveRecordingStillReturnsTheLiveTake()
    {
        // The penalty must apply to words the request did not ask for, or a live album could
        // never be played at all.
        var track = Wanted("Alive (Live at Wembley)", "Queen", 4.0);

        string best = Best(track,
            Hit("Queen - Alive (Official Audio)", "Queen", 4.0),
            Hit("Queen - Alive (Live at Wembley)", "Queen", 4.0));

        Assert.Equal("Queen - Alive (Live at Wembley)", best);
    }

    [Fact]
    public void ARemixOnlyLosesWhenTheOriginalWasWanted()
    {
        var original = Wanted("Levels", "Avicii", 3.3);
        Assert.Equal("Avicii - Levels (Original Mix)", Best(original,
            Hit("Avicii - Levels (Skrillex Remix)", "EDM Channel", 3.3),
            Hit("Avicii - Levels (Original Mix)", "Avicii", 3.3)));

        var remix = Wanted("Levels (Skrillex Remix)", "Avicii", 3.3);
        Assert.Equal("Avicii - Levels (Skrillex Remix)", Best(remix,
            Hit("Avicii - Levels (Skrillex Remix)", "EDM Channel", 3.3),
            Hit("Avicii - Levels (Original Mix)", "Avicii", 3.3)));
    }

    [Fact]
    public void ATrackWithNoKnownDurationIsStillRankedByWording()
    {
        var track = Track.ForProvider(new ProviderRef("s", "x"), "Creep", new[] { "Radiohead" }, TimeSpan.Zero);

        string best = Best(track,
            Hit("Creep (Karaoke)", "Karaoke Hits", 4.0),
            Hit("Radiohead - Creep (Official Audio)", "Radiohead", 4.0));

        Assert.Equal("Radiohead - Creep (Official Audio)", best);
    }

    [Fact]
    public void AccentsAndPunctuationDoNotStopAMatch()
    {
        var track = Wanted("Despacito", "Luis Fonsi", 3.8);

        string best = Best(track,
            Hit("Some Other Song", "Random", 3.8),
            Hit("Luis Fonsi – Despacito (Audio Oficial)", "LuisFonsiVEVO", 3.8));

        Assert.Equal("Luis Fonsi – Despacito (Audio Oficial)", best);
        Assert.Equal("beyonce halo", CandidateRanker.Normalize("Beyoncé — Halo!"));
    }

    [Fact]
    public void RankingIsStableForCandidatesThatScoreTheSame()
    {
        var track = Wanted("Untitled", "Unknown");
        var candidates = Enumerable.Range(0, 4).Select(i => Hit("take " + i, "channel", 3.3)).ToArray();

        var ranked = CandidateRanker.Rank(track, candidates);

        Assert.Equal(candidates.Select(c => c.Title), ranked.Select(c => c.Title));
    }

    [Fact]
    public void ASingleCandidateIsReturnedUnchanged()
    {
        var track = Wanted("Anything", "Anyone");
        var only = new[] { Hit("Anything (Karaoke)", "x", 9) };

        Assert.Same(only, CandidateRanker.Rank(track, only));
    }
}
