using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using AxePower.Core.Models;

namespace AxePower.Core.Services;

public class CacheCleanerService : ICacheCleanerService
{
    private readonly LogService _log;

    public CacheCleanerService(LogService log)
    {
        _log = log;
    }

    private List<(string Name, string Description, string Path)> GetTargetDirectories()
    {
        // These probes cannot throw (known folders and Directory.Exists), so they need no try/catch.
        var list = new List<(string Name, string Description, string Path)>();

        // 1. User Temp
        var userTemp = Path.GetTempPath();
        if (Directory.Exists(userTemp))
        {
            list.Add(("User Temp Files", "Temporary cache created by user applications and installers.", userTemp));
        }

        // 2. Windows Temp
        var winDir = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
        var winTemp = Path.Combine(winDir, "Temp");
        if (Directory.Exists(winTemp))
        {
            list.Add(("Windows System Temp", "Temporary system files generated by Windows and updates.", winTemp));
        }

        // 3. DirectX Shader Cache
        var localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        var d3dCache = Path.Combine(localAppData, "D3DSCache");
        if (Directory.Exists(d3dCache))
        {
            list.Add(("DirectX Shader Cache", "Compiled GPU shaders. Clearing fixes graphics glitches and stutter.", d3dCache));
        }

        // 4. Windows Crash Dumps
        var crashDumps = Path.Combine(localAppData, "CrashDumps");
        if (Directory.Exists(crashDumps))
        {
            list.Add(("Application Crash Dumps", "Memory dump files from crashed applications.", crashDumps));
        }

        // 5. Windows Delivery Optimization Cache
        var delivOpt = Path.Combine(winDir, "SoftwareDistribution", "DeliveryOptimization");
        if (Directory.Exists(delivOpt))
        {
            list.Add(("Delivery Optimization Cache", "Cached peer-to-peer Windows update installation files.", delivOpt));
        }

        return list;
    }

    public async Task<List<CacheCategorySummary>> AnalyzeCachesAsync()
    {
        return await Task.Run(() =>
        {
            var summaries = new List<CacheCategorySummary>();
            var targets = GetTargetDirectories();

            foreach (var target in targets)
            {
                var summary = new CacheCategorySummary
                {
                    Name = target.Name,
                    Description = target.Description,
                    DirectoryPath = target.Path,
                    IsSelected = true
                };

                try
                {
                    if (Directory.Exists(target.Path))
                    {
                        var dirInfo = new DirectoryInfo(target.Path);
                        long size = 0;
                        int count = 0;

                        // Enumerate top-level and sub files safely
                        foreach (var file in dirInfo.EnumerateFiles("*", SearchOption.AllDirectories))
                        {
                            try
                            {
                                size += file.Length;
                                count++;
                            }
                            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { /* Deleted or locked while we counted: left out of the estimate. */ }
                        }

                        summary.TotalSizeBytes = size;
                        summary.FileCount = count;
                    }
                }
                catch (Exception ex)
                {
                    _log.LogWarning($"[CacheCleaner] Could not scan directory '{target.Path}': {ex.Message}");
                }

                summaries.Add(summary);
            }

            return summaries;
        });
    }

    public async Task<CacheCleanResult> CleanCachesAsync(IEnumerable<CacheCategorySummary> categoriesToClean)
    {
        return await Task.Run(() =>
        {
            var result = new CacheCleanResult();

            foreach (var category in categoriesToClean.Where(c => c.IsSelected))
            {
                if (string.IsNullOrWhiteSpace(category.DirectoryPath) || !Directory.Exists(category.DirectoryPath))
                {
                    continue;
                }

                _log.LogInfo($"[CacheCleaner] Cleaning '{category.Name}' at '{category.DirectoryPath}'...");

                try
                {
                    var dirInfo = new DirectoryInfo(category.DirectoryPath);

                    // Delete files
                    foreach (var file in dirInfo.EnumerateFiles("*", SearchOption.AllDirectories))
                    {
                        try
                        {
                            long len = file.Length;
                            file.Attributes = FileAttributes.Normal;
                            file.Delete();
                            result.BytesCleaned += len;
                            result.FilesDeleted++;
                        }
                        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
                        {
                            // In use or access denied: skipped, and counted so the result says so.
                            result.FilesSkipped++;
                        }
                    }

                    // Delete empty subdirectories (never delete root target folder itself)
                    foreach (var subDir in dirInfo.EnumerateDirectories("*", SearchOption.AllDirectories).OrderByDescending(d => d.FullName.Length))
                    {
                        try
                        {
                            if (!subDir.EnumerateFileSystemInfos().Any())
                            {
                                subDir.Delete(false);
                            }
                        }
                        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { /* Best-effort: an emptied folder that is still in use stays. */ }
                    }
                }
                catch (Exception ex)
                {
                    _log.LogWarning($"[CacheCleaner] Error cleaning '{category.Name}': {ex.Message}");
                }
            }

            _log.LogInfo($"[CacheCleaner] Clean complete: {result.FormattedCleanedSize} freed ({result.FilesDeleted} deleted, {result.FilesSkipped} skipped in-use).");
            return result;
        });
    }
}
