using System;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using AxePower.Core.Models.Music;
using YoutubeExplode;
using YoutubeExplode.Videos.ClosedCaptions;

namespace AxePower.Core.Services.Music;

/// <summary>
/// Best-effort lyric fallback backed by YouTube's timed captions and YouTube Music's official
/// lyric panel.
/// Manual captions are preferred over generated captions, with English, Hindi and Punjabi
/// preferred when a video exposes several otherwise-equivalent tracks.
/// </summary>
public sealed class YouTubeCaptionLyricsProvider : IYouTubeCaptionLyricsProvider
{
    private static readonly Regex Whitespace = new(@"\s+", RegexOptions.Compiled);
    private static readonly HttpClient MusicClient = CreateMusicClient();

    private readonly YoutubeClient _youtube;
    private readonly LogService _log;

    public YouTubeCaptionLyricsProvider(LogService log)
        : this(new YoutubeClient(), log)
    {
    }

    internal YouTubeCaptionLyricsProvider(YoutubeClient youtube, LogService log)
    {
        _youtube = youtube;
        _log = log;
    }

    public async Task<LyricsResult?> GetLyricsAsync(string videoId, CancellationToken ct = default)
    {
        if (string.IsNullOrWhiteSpace(videoId)) return null;

        try
        {
            var manifest = await _youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, ct);
            var trackInfo = manifest.Tracks
                .OrderBy(track => track.IsAutoGenerated)
                .ThenBy(track => LanguageRank(track.Language.Code))
                .FirstOrDefault();
            if (trackInfo is null) return await GetOfficialLyricsAsync(videoId, ct);

            ClosedCaptionTrack captionTrack = await _youtube.Videos.ClosedCaptions.GetAsync(trackInfo, ct);
            var lines = new List<LyricLine>(captionTrack.Captions.Count);
            string? previous = null;
            foreach (var caption in captionTrack.Captions.OrderBy(caption => caption.Offset))
            {
                ct.ThrowIfCancellationRequested();
                string text = Clean(caption.Text);
                if (text.Length == 0 || string.Equals(text, previous, StringComparison.Ordinal)) continue;

                lines.Add(new LyricLine(caption.Offset, text));
                previous = text;
            }

            if (lines.Count > 0) return new LyricsResult("YouTube captions", lines);
            return await GetOfficialLyricsAsync(videoId, ct);
        }
        catch (OperationCanceledException)
        {
            throw;
        }
        catch (Exception ex)
        {
            _log.LogWarning($"[Music] YouTube caption lyrics lookup failed: {ex.Message}");
            return null;
        }
    }

    /// <summary>
    /// Reads the public lyrics tab used by music.youtube.com. It does not invent timestamps:
    /// official lyrics without timing are returned as plain lyrics and displayed as such.
    /// </summary>
    private static async Task<LyricsResult?> GetOfficialLyricsAsync(string videoId, CancellationToken ct)
    {
        var context = new
        {
            client = new
            {
                clientName = "WEB_REMIX",
                clientVersion = "1.20260213.01.00",
                hl = "en"
            }
        };

        using var nextRequest = JsonRequest(
            "https://music.youtube.com/youtubei/v1/next",
            new { context, videoId });
        using var nextResponse = await MusicClient.SendAsync(nextRequest, ct);
        if (!nextResponse.IsSuccessStatusCode) return null;

        await using var nextStream = await nextResponse.Content.ReadAsStreamAsync(ct);
        using var nextDocument = await JsonDocument.ParseAsync(nextStream, cancellationToken: ct);
        string? browseId = FindLyricsBrowseId(nextDocument.RootElement);
        if (string.IsNullOrWhiteSpace(browseId)) return null;

        using var browseRequest = JsonRequest(
            "https://music.youtube.com/youtubei/v1/browse",
            new { context, browseId });
        using var browseResponse = await MusicClient.SendAsync(browseRequest, ct);
        if (!browseResponse.IsSuccessStatusCode) return null;

        await using var browseStream = await browseResponse.Content.ReadAsStreamAsync(ct);
        using var browseDocument = await JsonDocument.ParseAsync(browseStream, cancellationToken: ct);
        string lyrics = ReadOfficialLyrics(browseDocument.RootElement);
        return string.IsNullOrWhiteSpace(lyrics)
            ? null
            : new LyricsResult("YouTube Music", Array.Empty<LyricLine>(), lyrics);
    }

    private static HttpRequestMessage JsonRequest(string url, object payload)
    {
        var request = new HttpRequestMessage(HttpMethod.Post, url)
        {
            Content = new StringContent(JsonSerializer.Serialize(payload), Encoding.UTF8, "application/json")
        };
        request.Headers.UserAgent.ParseAdd(
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36");
        return request;
    }

    private static string? FindLyricsBrowseId(JsonElement root)
    {
        if (!root.TryGetProperty("contents", out var contents)
            || !contents.TryGetProperty("singleColumnMusicWatchNextResultsRenderer", out var singleColumn)
            || !singleColumn.TryGetProperty("tabbedRenderer", out var tabbed)
            || !tabbed.TryGetProperty("watchNextTabbedResultsRenderer", out var results)
            || !results.TryGetProperty("tabs", out var tabs))
        {
            return null;
        }

        foreach (var tab in tabs.EnumerateArray())
        {
            if (!tab.TryGetProperty("tabRenderer", out var renderer)) continue;
            string? title = renderer.TryGetProperty("title", out var titleValue)
                ? titleValue.GetString()
                : null;
            if (!renderer.TryGetProperty("endpoint", out var endpoint)
                || !endpoint.TryGetProperty("browseEndpoint", out var browse)
                || !browse.TryGetProperty("browseId", out var idValue)) continue;

            string? id = idValue.GetString();
            if (!string.IsNullOrWhiteSpace(id)
                && (string.Equals(title, "Lyrics", StringComparison.OrdinalIgnoreCase)
                    || id.StartsWith("MPLY", StringComparison.Ordinal)))
            {
                return id;
            }
        }

        return null;
    }

    private static string ReadOfficialLyrics(JsonElement root)
    {
        if (!root.TryGetProperty("contents", out var contents)
            || !contents.TryGetProperty("sectionListRenderer", out var sectionList)
            || !sectionList.TryGetProperty("contents", out var sections))
        {
            return string.Empty;
        }

        var builder = new StringBuilder();
        foreach (var section in sections.EnumerateArray())
        {
            if (!section.TryGetProperty("musicDescriptionShelfRenderer", out var shelf)
                || !shelf.TryGetProperty("description", out var description)
                || !description.TryGetProperty("runs", out var runs)) continue;

            foreach (var run in runs.EnumerateArray())
            {
                if (run.TryGetProperty("text", out var text)) builder.Append(text.GetString());
            }
        }

        return builder.ToString().Trim();
    }

    private static HttpClient CreateMusicClient() => new() { Timeout = TimeSpan.FromSeconds(8) };

    private static int LanguageRank(string? code)
    {
        string language = code?.Split('-', '_')[0].ToLowerInvariant() ?? string.Empty;
        return language switch
        {
            "en" => 0,
            "hi" => 1,
            "pa" => 2,
            _ => 3
        };
    }

    private static string Clean(string text) =>
        Whitespace.Replace(WebUtility.HtmlDecode(text ?? string.Empty), " ").Trim();
}
